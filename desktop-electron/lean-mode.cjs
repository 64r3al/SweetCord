function buildLeanModeScript(settings) {
  const config = {
    leanMode: settings?.leanMode === true,
    reduceMotion: settings?.reduceMotion === true,
    hideProfileDecorations: settings?.hideProfileDecorations === true,
    staticAnimatedAvatars: settings?.staticAnimatedAvatars === true
  };

  const body = [
    '"use strict";',
    'const root = document.documentElement;',
    'if (!root) return;',
    'const styleId = "sweetcord-lean-mode-style";',
    'let style = document.getElementById(styleId);',
    'if (!style) { style = document.createElement("style"); style.id = styleId; (document.head || root).appendChild(style); }',
    'if (style.textContent !== css) style.textContent = css;',
    'root.classList.toggle("sweetcord-lean-mode", cfg.leanMode);',
    'root.classList.toggle("sweetcord-reduced-motion", cfg.reduceMotion);',
    'root.classList.toggle("sweetcord-trim-profile-decorations", cfg.hideProfileDecorations);',
    'const previousStaticState = window.__sweetCordStaticAvatarState;',
    'window.__sweetCordStaticAvatarState = cfg.staticAnimatedAvatars;',
    'const avatarSelector = \'img[src*="/avatars/"], img[data-sweetcord-original-src]\';',
    'const clearSavedAvatar = (img) => { img.removeAttribute("data-sweetcord-original-src"); img.removeAttribute("data-sweetcord-original-srcset"); img.removeAttribute("data-sweetcord-static-src"); };',
    'const normalizeAvatar = (img) => {',
    '  if (!(img instanceof HTMLImageElement)) return;',
    '  const source = img.getAttribute("src") || "";',
    '  const savedSource = img.getAttribute("data-sweetcord-original-src");',
    '  const staticSource = img.getAttribute("data-sweetcord-static-src");',
    '  const failedSource = img.getAttribute("data-sweetcord-static-failed-src");',
    '  if (failedSource && failedSource !== source) img.removeAttribute("data-sweetcord-static-failed-src");',
    '  else if (cfg.staticAnimatedAvatars && failedSource === source) return;',
    '  const pathOnly = source.split(/[?#]/, 1)[0].toLowerCase();',
    '  const finalSegment = pathOnly.slice(pathOnly.lastIndexOf("/") + 1);',
    '  const isAnimatedAvatar = pathOnly.includes("/avatars/") && finalSegment.startsWith("a_") && finalSegment.endsWith(".gif");',
    '  if (!cfg.staticAnimatedAvatars) {',
    '    if (savedSource && staticSource && source === staticSource) {',
    '      img.setAttribute("src", savedSource);',
    '      const originalSet = img.getAttribute("data-sweetcord-original-srcset") || "";',
    '      if (originalSet) img.setAttribute("srcset", originalSet); else img.removeAttribute("srcset");',
    '    }',
    '    clearSavedAvatar(img); img.removeAttribute("data-sweetcord-static-failed-src");',
    '    return;',
    '  }',
    '  if (isAnimatedAvatar) {',
    '    if (!savedSource || savedSource !== source) {',
    '      img.setAttribute("data-sweetcord-original-src", source);',
    '      img.setAttribute("data-sweetcord-original-srcset", img.getAttribute("srcset") || "");',
    '    }',
    '    const queryStart = source.search(/[?#]/);',
    '    const base = queryStart < 0 ? source : source.slice(0, queryStart);',
    '    const suffix = queryStart < 0 ? "" : source.slice(queryStart);',
    '    const stillSource = base.slice(0, -4) + ".png" + suffix;',
    '    img.setAttribute("data-sweetcord-static-src", stillSource);',
    '    img.removeAttribute("srcset");',
    '    if (source !== stillSource) {',
    '      img.addEventListener("error", () => {',
    '        if (img.getAttribute("src") !== stillSource) return;',
    '        const original = img.getAttribute("data-sweetcord-original-src");',
    '        const originalSet = img.getAttribute("data-sweetcord-original-srcset") || "";',
    '        if (original) { img.setAttribute("data-sweetcord-static-failed-src", original); img.setAttribute("src", original); }',
    '        if (originalSet) img.setAttribute("srcset", originalSet); else img.removeAttribute("srcset");',
    '        clearSavedAvatar(img);',
    '      }, { once: true });',
    '      img.setAttribute("src", stillSource);',
    '    }',
    '  } else if (savedSource && staticSource && source !== staticSource) {',
    '    // Discord reused the element for a different non-animated asset; never restore stale URLs.',
    '    clearSavedAvatar(img);',
    '  }',
    '};',
    'const processTree = (node) => {',
    '  if (!(node instanceof Element)) return;',
    '  if (node.matches(avatarSelector)) normalizeAvatar(node);',
    '  if (node.querySelectorAll) node.querySelectorAll(avatarSelector).forEach(normalizeAvatar);',
    '};',
    'const processExistingAvatars = () => document.querySelectorAll(avatarSelector).forEach(normalizeAvatar);',
    'if (!window.__sweetCordAvatarObserverInstalled) {',
    '  const pendingNodes = new Set();',
    '  const pendingImages = new Set();',
    '  let frameQueued = false;',
    '  const flushPending = () => {',
    '    frameQueued = false;',
    '    for (const image of pendingImages) normalizeAvatar(image);',
    '    const queuedNodes = Array.from(pendingNodes);',
    '    for (const node of queuedNodes) {',
    '      let parent = node.parentElement;',
    '      let coveredByQueuedAncestor = false;',
    '      while (parent) { if (pendingNodes.has(parent)) { coveredByQueuedAncestor = true; break; } parent = parent.parentElement; }',
    '      if (!coveredByQueuedAncestor) processTree(node);',
    '    }',
    '    pendingImages.clear();',
    '    pendingNodes.clear();',
    '  };',
    '  const queueFlush = () => { if (!frameQueued) { frameQueued = true; window.requestAnimationFrame(flushPending); } };',
    '  const observer = new MutationObserver((records) => {',
    '    for (const record of records) {',
    '      if (record.type === "attributes") {',
    '        if (record.target instanceof HTMLImageElement && record.target.matches(avatarSelector)) pendingImages.add(record.target);',
    '      } else {',
    '        for (const node of record.addedNodes) if (node instanceof Element) pendingNodes.add(node);',
    '      }',
    '    }',
    '    if (pendingNodes.size || pendingImages.size) queueFlush();',
    '  });',
    '  observer.observe(root, { childList: true, subtree: true, attributes: true, attributeFilter: ["src"] });',
    '  window.__sweetCordAvatarObserverInstalled = true;',
    '}',
    'if (previousStaticState !== cfg.staticAnimatedAvatars || !window.__sweetCordAvatarInitialScanDone) {',
    '  processExistingAvatars();',
    '  window.__sweetCordAvatarInitialScanDone = true;',
    '}',
  ].join("\n");

  return "(function(){\nconst cfg = " + JSON.stringify(config) + ";\nconst css = " + JSON.stringify(LEAN_STYLES) + ";\n" + body + "\n})();";
}

module.exports = { buildLeanModeScript };
